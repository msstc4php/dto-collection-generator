<?php

declare(strict_types=1);

namespace MSSTC4PHP\DtoCollectionGenerator\Infrastructure\Writer;

use Closure;
use JsonException;
use LogicException;
use MSSTC4PHP\DtoCollectionGenerator\Application\Generate\ChangeKind;
use MSSTC4PHP\DtoCollectionGenerator\Application\Generate\FileChange;
use MSSTC4PHP\DtoCollectionGenerator\Application\Generate\GeneratedFile;
use MSSTC4PHP\DtoCollectionGenerator\Application\Generate\WritePlan;
use MSSTC4PHP\DtoCollectionGenerator\Application\Port\FileWriter;
use MSSTC4PHP\DtoCollectionGenerator\Application\Port\WriteFailed;
use MSSTC4PHP\DtoCollectionGenerator\Domain\Shared\Path;

/**
 * Writes generated files atomically and remembers them in a manifest, so a file whose spec is gone can be deleted
 * when nobody edited it. A file without the generated header is never overwritten.
 *
 * @internal
 */
final class FilesystemWriter implements FileWriter
{
    private const GENERATOR = 'msstc4php/dto-collection-generator';

    private const TEMPORARY_PREFIX = '.dto-collection-generator-tmp-';

    private const GENERATED = '~\A<\?php\r?\n(?:\r?\n)?// @generated by msstc4php/dto-collection-generator~';

    /** @var Closure(string): ?string */
    private readonly Closure $identity;

    /**
     * @param (Closure(string $path): ?string)|null $identity a file's identity ("device:inode"), null when unknown
     */
    public function __construct(?Closure $identity = null)
    {
        $this->identity = $identity ?? static fn (string $path): ?string => self::identity(@stat($path));
    }

    /**
     * @param array{dev: int, ino: int}|false $stat as stat() returns it
     */
    public static function identity(array|false $stat): ?string
    {
        // Some file systems and builds report inode 0 for every file: no identity then.
        if ($stat === false || $stat['ino'] === 0) {
            return null;
        }

        return $stat['dev'] . ':' . $stat['ino'];
    }

    public function plan(string $manifestPath, array $files): WritePlan
    {
        $changes = [];
        $paths = [];
        foreach ($files as $file) {
            $paths[strtolower($file->path)] ??= $file->path;
            $first = $paths[strtolower($file->path)];
            if ($first !== $file->path) {
                $changes[] = new FileChange(ChangeKind::Conflict, $file->path, sprintf(
                    'its path differs from %s only in letter case, which case-insensitive file systems cannot hold',
                    Path::within(Path::directory($manifestPath), $first) ?? $first,
                ));

                continue;
            }
            $changes[] = $this->compare($file);
        }

        $old = $this->readManifest($manifestPath);
        $directory = Path::directory($manifestPath);
        // The manifest is a file in the project, so it is not trusted: an entry counts only inside the config's
        // directory or a directory this run writes into; any other one is dropped without a word.
        $scopes = [$directory, ...array_map(static fn (GeneratedFile $file): string => Path::directory($file->path), $files)];
        // Files written in this run, by device and inode: on a case-insensitive file system, renaming App\ItemList to
        // App\Itemlist rewrites the very file the old entry names (as does any other spelling of it), and deleting
        // that entry would delete the class.
        $written = array_map(fn (GeneratedFile $file): ?string => ($this->identity)($file->path), $files);
        // $old is sorted by path, so the deletions come in a stable order.
        foreach ($old as $path => $hash) {
            $current = is_file($path) ? file_get_contents($path) : false;
            if ($current === false || !$this->isInside($path, $scopes) || $this->isWrittenNow($path, $written, $paths)) {
                continue;
            }
            // Only our own generated files are deleted; a PHP file that lost the header earns a warning.
            if (preg_match(self::GENERATED, $current) !== 1 || !str_ends_with($path, '.php')) {
                if (str_ends_with($path, '.php')) {
                    $changes[] = new FileChange(ChangeKind::Abandoned, $path, 'it was generated earlier and its spec is gone, but it no longer starts with the generated header, so it was left alone');
                }

                continue;
            }
            $changes[] = hash('sha256', $this->normalized($current)) === $hash
                ? new FileChange(ChangeKind::Delete, $path)
                : new FileChange(ChangeKind::Conflict, $path, 'its spec is gone, but it was edited after generation; delete it yourself');
        }

        $manifest = is_file($manifestPath) ? file_get_contents($manifestPath) : false;
        $expected = $this->encodeManifest($manifestPath, $this->hashes($files));
        // Without a manifest and with nothing to generate, there is nothing to remember yet.
        $outdated = $manifest === false ? $files !== [] : $this->normalized($manifest) !== $expected;

        return new WritePlan($changes, $outdated);
    }

    public function apply(WritePlan $plan, string $manifestPath, array $files): void
    {
        if ($plan->hasConflicts()) {
            throw new LogicException('A plan with conflicts must not be applied');
        }
        $contents = [];
        foreach ($files as $file) {
            $contents[$file->path] = $file->contents;
        }
        // Until the run completes, the manifest lists old and new files, so an interrupted run leaves no orphan.
        $this->writeManifest($manifestPath, array_merge($this->readManifest($manifestPath), $this->hashes($files)));
        foreach ($plan->changes as $change) {
            if ($change->kind === ChangeKind::Delete) {
                $this->delete($change->path);
            } elseif ($change->kind === ChangeKind::Create || $change->kind === ChangeKind::Update) {
                $this->write($change->path, $contents[$change->path] ?? throw new LogicException('The plan names a file it was not made for: ' . $change->path));
            }
        }
        $this->writeManifest($manifestPath, $this->hashes($files));
    }

    public function isGenerated(string $path): bool
    {
        $contents = is_file($path) ? file_get_contents($path) : false;

        return $contents !== false && preg_match(self::GENERATED, $contents) === 1;
    }

    private function compare(GeneratedFile $file): FileChange
    {
        $current = is_file($file->path) ? file_get_contents($file->path) : false;
        if ($current === false) {
            return new FileChange(ChangeKind::Create, $file->path);
        }
        if ($this->normalized($current) === $this->normalized($file->contents)) {
            return new FileChange(ChangeKind::Unchanged, $file->path);
        }
        if (!$this->isGenerated($file->path)) {
            return new FileChange(ChangeKind::Conflict, $file->path, 'it exists and was not generated by dto-collection-generator; move or delete it');
        }

        return new FileChange(ChangeKind::Update, $file->path);
    }

    /**
     * @param list<GeneratedFile> $files
     *
     * @return array<string, string> absolute path => sha256 of the LF contents
     */
    private function hashes(array $files): array
    {
        $hashes = [];
        foreach ($files as $file) {
            $hashes[$file->path] = hash('sha256', $this->normalized($file->contents));
        }

        return $hashes;
    }

    private function normalized(string $contents): string
    {
        return str_replace("\r\n", "\n", $contents);
    }

    /**
     * @return array<string, string> absolute path => hash; empty when there is no usable manifest
     */
    private function readManifest(string $manifestPath): array
    {
        $content = is_file($manifestPath) ? file_get_contents($manifestPath) : false;
        if ($content === false) {
            return [];
        }

        try {
            $data = json_decode($content, true, flags: JSON_THROW_ON_ERROR);
        } catch (JsonException) {
            return [];
        }
        $files = is_array($data) ? $data['files'] ?? [] : [];
        $hashes = [];
        foreach (is_array($files) ? $files : [] as $path => $hash) {
            if (is_string($hash)) {
                $hashes[Path::resolve(Path::directory($manifestPath), (string) $path)] = $hash;
            }
        }
        ksort($hashes);

        return $hashes;
    }

    /**
     * @param array<string, string> $hashes
     */
    private function writeManifest(string $manifestPath, array $hashes): void
    {
        $this->write($manifestPath, $this->encodeManifest($manifestPath, $hashes));
    }

    /**
     * @param array<string, string> $hashes
     */
    private function encodeManifest(string $manifestPath, array $hashes): string
    {
        $directory = Path::directory($manifestPath);
        $relative = [];
        foreach ($hashes as $path => $hash) {
            $relative[Path::relative($directory, $path) ?? $path] = $hash;
        }
        ksort($relative, SORT_STRING);

        return json_encode(
            ['generator' => self::GENERATOR, 'files' => (object) $relative],
            JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR,
        ) . "\n";
    }

    /**
     * @param list<string> $scopes
     */
    private function isInside(string $path, array $scopes): bool
    {
        foreach ($scopes as $scope) {
            if (Path::within($scope, $path) !== null) {
                return true;
            }
        }

        return false;
    }

    /**
     * @param list<?string> $written identities of this run's files; null for those that do not exist yet
     * @param array<string, string> $paths lower-case path => path of this run's files
     */
    private function isWrittenNow(string $path, array $written, array $paths): bool
    {
        $identity = ($this->identity)($path);
        if ($identity !== null) {
            return in_array($identity, $written, true);
        }

        // Unknown identity: the same path in another letter case may be the same file on this file system.
        return isset($paths[strtolower($path)]);
    }

    private function write(string $path, string $contents): void
    {
        $directory = Path::directory($path);
        if (!is_dir($directory) && !@mkdir($directory, recursive: true)) {
            throw new WriteFailed(sprintf('Cannot create the directory %s', $directory));
        }
        // A temporary file in the same directory, so the rename is atomic and a reader never sees half a file.
        // Not tempnam(): it creates the file with mode 0600, which the rename would keep.
        $temporary = $directory . '/' . self::TEMPORARY_PREFIX . bin2hex(random_bytes(8));
        if (@file_put_contents($temporary, $contents) === false || !@rename($temporary, $path)) {
            @unlink($temporary);

            throw new WriteFailed(sprintf('Cannot write %s', $path));
        }
    }

    private function delete(string $path): void
    {
        if (!@unlink($path)) {
            throw new WriteFailed(sprintf('Cannot delete %s', $path));
        }
    }
}
