<?php

declare(strict_types=1);

namespace MSSTC4PHP\DtoCollectionGenerator\Tests\Integration\Infrastructure;

use LogicException;
use MSSTC4PHP\DtoCollectionGenerator\Application\Generate\FileChange;
use MSSTC4PHP\DtoCollectionGenerator\Application\Generate\GeneratedFile;
use MSSTC4PHP\DtoCollectionGenerator\Application\Generate\WritePlan;
use MSSTC4PHP\DtoCollectionGenerator\Infrastructure\Writer\FilesystemWriter;
use MSSTC4PHP\DtoCollectionGenerator\Tests\Support\TemporaryDirectory;
use PHPUnit\Framework\TestCase;

final class FilesystemWriterTest extends TestCase
{
    private const HEADER = "<?php\n\n// @generated by msstc4php/dto-collection-generator — DO NOT EDIT\n";

    private TemporaryDirectory $directory;

    private string $manifest;

    protected function setUp(): void
    {
        $this->directory = new TemporaryDirectory();
        $this->manifest = $this->directory->path . '/.dto-collection-generator.manifest.json';
    }

    protected function tearDown(): void
    {
        $this->directory->remove();
    }

    public function testCreateThenUnchanged(): void
    {
        $files = [$this->file('src/ItemList.php', 'one'), $this->file('src/Deep/TagList.php', 'two')];
        $writer = new FilesystemWriter();

        $plan = $writer->plan($this->manifest, $files);
        self::assertSame([['create', 'src/ItemList.php'], ['create', 'src/Deep/TagList.php']], $this->changes($plan));
        self::assertFalse($plan->isUpToDate());
        $writer->apply($plan, $this->manifest, $files);

        self::assertStringEqualsFile($this->directory->path . '/src/Deep/TagList.php', self::HEADER . 'two');
        $replan = $writer->plan($this->manifest, $files);
        self::assertSame([['unchanged', 'src/ItemList.php'], ['unchanged', 'src/Deep/TagList.php']], $this->changes($replan));
        self::assertTrue($replan->isUpToDate());
        self::assertSame([], glob($this->directory->path . '/src/{,*/}.*.tmp', GLOB_BRACE));
    }

    public function testManifest(): void
    {
        $files = [$this->file('src/ItemList.php', 'one'), $this->file('src/AList.php', 'two')];
        $writer = new FilesystemWriter();
        $writer->apply($writer->plan($this->manifest, $files), $this->manifest, $files);

        self::assertSame(
            "{\n    \"generator\": \"msstc4php/dto-collection-generator\",\n    \"files\": {\n"
            . '        "src/AList.php": "' . hash('sha256', self::HEADER . 'two') . "\",\n"
            . '        "src/ItemList.php": "' . hash('sha256', self::HEADER . 'one') . "\"\n    }\n}\n",
            file_get_contents($this->manifest),
        );
    }

    public function testUpdate(): void
    {
        $writer = new FilesystemWriter();
        $old = [$this->file('src/ItemList.php', 'one')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);
        $new = [$this->file('src/ItemList.php', 'changed')];

        $plan = $writer->plan($this->manifest, $new);
        self::assertSame([['update', 'src/ItemList.php']], $this->changes($plan));
        $writer->apply($plan, $this->manifest, $new);
        self::assertStringEqualsFile($this->directory->path . '/src/ItemList.php', self::HEADER . 'changed');
    }

    public function testGeneratedFileWithoutManifestIsUpdated(): void
    {
        $this->directory->write('src/ItemList.php', self::HEADER . 'old');

        self::assertSame([['update', 'src/ItemList.php']], $this->changes((new FilesystemWriter())->plan($this->manifest, [$this->file('src/ItemList.php', 'new')])));
    }

    public function testHandWrittenFileIsAConflict(): void
    {
        $this->directory->write('src/ItemList.php', "<?php\n\nfinal class ItemList {}\n");
        $plan = (new FilesystemWriter())->plan($this->manifest, [$this->file('src/ItemList.php', 'one')]);

        self::assertSame([['conflict', 'src/ItemList.php']], $this->changes($plan));
        self::assertSame('it exists and was not generated by dto-collection-generator; move or delete it', $plan->changes[0]->reason);
        self::assertTrue($plan->hasConflicts());
        self::assertFalse($plan->isUpToDate());
    }

    public function testRemovedSpecDeletesItsFile(): void
    {
        $writer = new FilesystemWriter();
        $old = [$this->file('src/ItemList.php', 'one'), $this->file('src/TagList.php', 'two')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);
        $new = [$this->file('src/ItemList.php', 'one')];

        $plan = $writer->plan($this->manifest, $new);
        self::assertSame([['unchanged', 'src/ItemList.php'], ['delete', 'src/TagList.php']], $this->changes($plan));
        $writer->apply($plan, $this->manifest, $new);
        self::assertFileDoesNotExist($this->directory->path . '/src/TagList.php');
        self::assertTrue($writer->plan($this->manifest, $new)->isUpToDate());
    }

    public function testEditedFileOfARemovedSpecIsKept(): void
    {
        $writer = new FilesystemWriter();
        $old = [$this->file('src/TagList.php', 'two')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);
        $this->directory->write('src/TagList.php', self::HEADER . 'two, edited');

        $plan = $writer->plan($this->manifest, []);
        self::assertSame([['conflict', 'src/TagList.php']], $this->changes($plan));
        self::assertSame('its spec is gone, but it was edited after generation; delete it yourself', $plan->changes[0]->reason);
    }

    public function testFileOfARemovedSpecThatIsAlreadyGoneIsIgnored(): void
    {
        $writer = new FilesystemWriter();
        $old = [$this->file('src/TagList.php', 'two')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);
        unlink($this->directory->path . '/src/TagList.php');

        $plan = $writer->plan($this->manifest, []);
        self::assertSame([], $this->changes($plan));
        self::assertFalse($plan->isUpToDate());
    }

    public function testLineEndingsDoNotMatter(): void
    {
        $writer = new FilesystemWriter();
        $files = [$this->file('src/ItemList.php', "one\ntwo\n")];
        $writer->apply($writer->plan($this->manifest, $files), $this->manifest, $files);
        $this->directory->write('src/ItemList.php', str_replace("\n", "\r\n", self::HEADER . "one\ntwo\n"));

        self::assertSame([['unchanged', 'src/ItemList.php']], $this->changes($writer->plan($this->manifest, $files)));
        self::assertSame([['delete', 'src/ItemList.php']], $this->changes($writer->plan($this->manifest, [])));
    }

    public function testPathsDifferingOnlyInCase(): void
    {
        $plan = (new FilesystemWriter())->plan($this->manifest, [$this->file('src/ItemList.php', 'one'), $this->file('src/itemlist.php', 'two')]);

        self::assertSame([['create', 'src/ItemList.php'], ['conflict', 'src/itemlist.php']], $this->changes($plan));
        self::assertSame('its path differs from src/ItemList.php only in letter case, which case-insensitive file systems cannot hold', $plan->changes[1]->reason);
    }

    public function testFilesOutsideTheManifestDirectory(): void
    {
        $outside = new TemporaryDirectory();
        $files = [new GeneratedFile($outside->path . '/ItemList.php', self::HEADER . 'one')];
        $writer = new FilesystemWriter();

        try {
            $writer->apply($writer->plan($this->manifest, $files), $this->manifest, $files);
            self::assertTrue($writer->plan($this->manifest, $files)->isUpToDate());
            self::assertStringContainsString(json_encode($outside->path . '/ItemList.php', JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES), (string) file_get_contents($this->manifest));
        } finally {
            $outside->remove();
        }
    }

    public function testApplyRefusesAPlanWithConflicts(): void
    {
        $this->directory->write('src/ItemList.php', "<?php\n");
        $files = [$this->file('src/ItemList.php', 'one')];
        $writer = new FilesystemWriter();

        $this->expectException(LogicException::class);
        $writer->apply($writer->plan($this->manifest, $files), $this->manifest, $files);
    }

    public function testUnreadableManifestCountsAsEmpty(): void
    {
        file_put_contents($this->manifest, 'not json');

        self::assertSame([['create', 'src/ItemList.php']], $this->changes((new FilesystemWriter())->plan($this->manifest, [$this->file('src/ItemList.php', 'one')])));
    }

    private function file(string $relativePath, string $body): GeneratedFile
    {
        return new GeneratedFile($this->directory->path . '/' . $relativePath, self::HEADER . $body);
    }

    /**
     * @return list<array{string, string}>
     */
    private function changes(WritePlan $plan): array
    {
        return array_map(
            fn (FileChange $change): array => [$change->kind->value, substr($change->path, strlen($this->directory->path) + 1)],
            $plan->changes,
        );
    }
}
