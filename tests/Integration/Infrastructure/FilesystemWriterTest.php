<?php

declare(strict_types=1);

namespace MSSTC4PHP\DtoCollectionGenerator\Tests\Integration\Infrastructure;

use LogicException;
use MSSTC4PHP\DtoCollectionGenerator\Application\Generate\ChangeKind;
use MSSTC4PHP\DtoCollectionGenerator\Application\Generate\FileChange;
use MSSTC4PHP\DtoCollectionGenerator\Application\Generate\GeneratedFile;
use MSSTC4PHP\DtoCollectionGenerator\Application\Generate\WritePlan;
use MSSTC4PHP\DtoCollectionGenerator\Application\Port\WriteFailed;
use MSSTC4PHP\DtoCollectionGenerator\Infrastructure\Writer\FilesystemWriter;
use MSSTC4PHP\DtoCollectionGenerator\Tests\Support\TemporaryDirectory;
use PHPUnit\Framework\TestCase;

final class FilesystemWriterTest extends TestCase
{
    private const HEADER = "<?php\n\n// @generated by msstc4php/dto-collection-generator — DO NOT EDIT\n";

    private TemporaryDirectory $directory;

    private string $manifest;

    protected function setUp(): void
    {
        $this->directory = new TemporaryDirectory();
        $this->manifest = $this->directory->path . '/.dto-collection-generator.manifest.json';
    }

    protected function tearDown(): void
    {
        $this->directory->remove();
    }

    public function testCreateThenUnchanged(): void
    {
        $files = [$this->file('src/ItemList.php', 'one'), $this->file('src/Deep/TagList.php', 'two')];
        $writer = new FilesystemWriter();

        $plan = $writer->plan($this->manifest, $files);
        self::assertSame([['create', 'src/ItemList.php'], ['create', 'src/Deep/TagList.php']], $this->changes($plan));
        self::assertFalse($plan->isUpToDate());
        $writer->apply($plan, $this->manifest, $files);

        self::assertStringEqualsFile($this->directory->path . '/src/Deep/TagList.php', self::HEADER . 'two');
        $replan = $writer->plan($this->manifest, $files);
        self::assertSame([['unchanged', 'src/ItemList.php'], ['unchanged', 'src/Deep/TagList.php']], $this->changes($replan));
        self::assertTrue($replan->isUpToDate());
        self::assertSame([], glob($this->directory->path . '/src/{,*/}.dto-collection-generator-tmp-*', GLOB_BRACE));
        // umask decides, as for any file PHP creates: tempnam()'s 0600 would hide the class from other users.
        self::assertSame(0o666 & ~umask(), fileperms($this->directory->path . '/src/ItemList.php') & 0o777);
    }

    public function testManifest(): void
    {
        $files = [$this->file('src/ItemList.php', 'one'), $this->file('src/AList.php', 'two')];
        $writer = new FilesystemWriter();
        $writer->apply($writer->plan($this->manifest, $files), $this->manifest, $files);

        self::assertSame(
            "{\n    \"generator\": \"msstc4php/dto-collection-generator\",\n    \"files\": {\n"
            . '        "src/AList.php": "' . hash('sha256', self::HEADER . 'two') . "\",\n"
            . '        "src/ItemList.php": "' . hash('sha256', self::HEADER . 'one') . "\"\n    }\n}\n",
            file_get_contents($this->manifest),
        );
    }

    public function testRenameThatOnlyChangesCaseKeepsTheFile(): void
    {
        $writer = new FilesystemWriter();
        $old = [$this->file('src/ItemList.php', 'one')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);
        // A case-insensitive file system (macOS, Windows) shows both spellings as one file; a hard link does here.
        link($this->directory->path . '/src/ItemList.php', $this->directory->path . '/src/Itemlist.php');
        $new = [$this->file('src/Itemlist.php', 'two')];

        $plan = $writer->plan($this->manifest, $new);
        self::assertSame([['update', 'src/Itemlist.php']], $this->changes($plan));
        $writer->apply($plan, $this->manifest, $new);
        self::assertStringEqualsFile($this->directory->path . '/src/Itemlist.php', self::HEADER . 'two');
    }

    public function testRenameThatOnlyChangesCaseOnACaseSensitiveFileSystem(): void
    {
        $writer = new FilesystemWriter();
        $old = [$this->file('src/ItemList.php', 'one')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);

        self::assertSame([['create', 'src/Itemlist.php'], ['delete', 'src/ItemList.php']], $this->changes($writer->plan($this->manifest, [$this->file('src/Itemlist.php', 'two')])));
    }

    public function testUnchangedFilesAreNotRewritten(): void
    {
        $writer = new FilesystemWriter();
        $files = [$this->file('src/ItemList.php', 'one')];
        $writer->apply($writer->plan($this->manifest, $files), $this->manifest, $files);
        touch($this->directory->path . '/src/ItemList.php', 1_000_000_000);

        $writer->apply($writer->plan($this->manifest, $files), $this->manifest, $files);

        clearstatcache();
        self::assertSame(1_000_000_000, filemtime($this->directory->path . '/src/ItemList.php'));
    }

    public function testUpdate(): void
    {
        $writer = new FilesystemWriter();
        $old = [$this->file('src/ItemList.php', 'one')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);
        $new = [$this->file('src/ItemList.php', 'changed')];

        $plan = $writer->plan($this->manifest, $new);
        self::assertSame([['update', 'src/ItemList.php']], $this->changes($plan));
        $writer->apply($plan, $this->manifest, $new);
        self::assertStringEqualsFile($this->directory->path . '/src/ItemList.php', self::HEADER . 'changed');
    }

    public function testGeneratedFileWithoutManifestIsUpdated(): void
    {
        $this->directory->write('src/ItemList.php', self::HEADER . 'old');

        self::assertSame([['update', 'src/ItemList.php']], $this->changes((new FilesystemWriter())->plan($this->manifest, [$this->file('src/ItemList.php', 'new')])));
    }

    public function testHandWrittenFileIsAConflict(): void
    {
        $this->directory->write('src/ItemList.php', "<?php\n\nfinal class ItemList {}\n");
        $plan = (new FilesystemWriter())->plan($this->manifest, [$this->file('src/ItemList.php', 'one')]);

        self::assertSame([['conflict', 'src/ItemList.php']], $this->changes($plan));
        self::assertSame('it exists and was not generated by dto-collection-generator; move or delete it', $plan->changes[0]->reason);
        self::assertTrue($plan->hasConflicts());
        self::assertFalse($plan->isUpToDate());
    }

    public function testRemovedSpecDeletesItsFile(): void
    {
        $writer = new FilesystemWriter();
        $old = [$this->file('src/ItemList.php', 'one'), $this->file('src/TagList.php', 'two')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);
        $new = [$this->file('src/ItemList.php', 'one')];

        $plan = $writer->plan($this->manifest, $new);
        self::assertSame([['unchanged', 'src/ItemList.php'], ['delete', 'src/TagList.php']], $this->changes($plan));
        $writer->apply($plan, $this->manifest, $new);
        self::assertFileDoesNotExist($this->directory->path . '/src/TagList.php');
        self::assertTrue($writer->plan($this->manifest, $new)->isUpToDate());
    }

    public function testEditedFileOfARemovedSpecIsKept(): void
    {
        $writer = new FilesystemWriter();
        $old = [$this->file('src/TagList.php', 'two')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);
        $this->directory->write('src/TagList.php', self::HEADER . 'two, edited');

        $plan = $writer->plan($this->manifest, []);
        self::assertSame([['conflict', 'src/TagList.php']], $this->changes($plan));
        self::assertSame('its spec is gone, but it was edited after generation; delete it yourself', $plan->changes[0]->reason);
    }

    public function testFileOfARemovedSpecThatIsAlreadyGoneIsIgnored(): void
    {
        $writer = new FilesystemWriter();
        $old = [$this->file('src/TagList.php', 'two')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);
        unlink($this->directory->path . '/src/TagList.php');

        $plan = $writer->plan($this->manifest, []);
        self::assertSame([], $this->changes($plan));
        self::assertFalse($plan->isUpToDate());
    }

    public function testEveryStaleFileIsLookedAt(): void
    {
        $writer = new FilesystemWriter();
        $old = [$this->file('src/A.php', 'a'), $this->file('src/B.php', 'b')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);
        unlink($this->directory->path . '/src/A.php');

        self::assertSame([['delete', 'src/B.php']], $this->changes($writer->plan($this->manifest, [])));
    }

    public function testLineEndingsDoNotMatter(): void
    {
        $writer = new FilesystemWriter();
        $files = [$this->file('src/ItemList.php', "one\ntwo\n")];
        $writer->apply($writer->plan($this->manifest, $files), $this->manifest, $files);
        $this->directory->write('src/ItemList.php', str_replace("\n", "\r\n", self::HEADER . "one\ntwo\n"));

        self::assertSame([['unchanged', 'src/ItemList.php']], $this->changes($writer->plan($this->manifest, $files)));
        self::assertSame([['delete', 'src/ItemList.php']], $this->changes($writer->plan($this->manifest, [])));
    }

    public function testPathsDifferingOnlyInCase(): void
    {
        $plan = (new FilesystemWriter())->plan($this->manifest, [$this->file('src/ItemList.php', 'one'), $this->file('src/itemlist.php', 'two'), $this->file('src/TagList.php', 'three')]);

        self::assertSame([['create', 'src/ItemList.php'], ['conflict', 'src/itemlist.php'], ['create', 'src/TagList.php']], $this->changes($plan));
        self::assertSame('its path differs from src/ItemList.php only in letter case, which case-insensitive file systems cannot hold', $plan->changes[1]->reason);
    }

    public function testFilesOutsideTheManifestDirectory(): void
    {
        $outside = new TemporaryDirectory();
        $files = [new GeneratedFile($outside->path . '/ItemList.php', self::HEADER . 'one')];
        $writer = new FilesystemWriter();

        try {
            $writer->apply($writer->plan($this->manifest, $files), $this->manifest, $files);
            self::assertTrue($writer->plan($this->manifest, $files)->isUpToDate());
            // Relative, so a committed manifest means the same on another machine.
            self::assertStringContainsString('"../' . basename($outside->path) . '/ItemList.php"', (string) file_get_contents($this->manifest));
        } finally {
            $outside->remove();
        }
    }

    public function testApplyRefusesAPlanWithConflicts(): void
    {
        $this->directory->write('src/ItemList.php', "<?php\n");
        $files = [$this->file('src/ItemList.php', 'one')];
        $writer = new FilesystemWriter();

        $this->expectException(LogicException::class);
        $writer->apply($writer->plan($this->manifest, $files), $this->manifest, $files);
    }

    public function testManifestEntriesForOtherFilesAreIgnored(): void
    {
        $outside = new TemporaryDirectory();
        $victims = [
            $outside->write('notes.txt', 'keep me'),
            $this->directory->write('src/HandWritten.php', "<?php\n\nfinal class HandWritten {}\n"),
            $this->directory->write('src/generated.txt', self::HEADER),
        ];
        $entries = [];
        foreach ($victims as $victim) {
            $entries[$victim] = hash('sha256', (string) file_get_contents($victim));
        }
        file_put_contents($this->manifest, json_encode(['generator' => 'msstc4php/dto-collection-generator', 'files' => $entries], JSON_THROW_ON_ERROR));
        $writer = new FilesystemWriter();

        try {
            $plan = $writer->plan($this->manifest, []);
            self::assertSame([ChangeKind::Abandoned, ChangeKind::Abandoned, ChangeKind::Abandoned], array_map(static fn (FileChange $change): ChangeKind => $change->kind, $plan->changes));
            $writer->apply($plan, $this->manifest, []);
            foreach ($victims as $victim) {
                self::assertFileExists($victim);
            }
        } finally {
            $outside->remove();
        }
    }

    public function testOnlyGeneratedStaleFilesAreDeleted(): void
    {
        $writer = new FilesystemWriter();
        $old = [$this->file('src/A.php', 'a'), $this->file('src/B.php', 'b')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);
        $this->directory->write('src/A.php', "<?php\n\nfinal class A {}\n");
        file_put_contents($this->manifest, str_replace(hash('sha256', self::HEADER . 'a'), hash('sha256', "<?php\n\nfinal class A {}\n"), (string) file_get_contents($this->manifest)));

        $plan = $writer->plan($this->manifest, []);
        self::assertSame([['abandoned', 'src/A.php'], ['delete', 'src/B.php']], $this->changes($plan));
        self::assertSame('it was generated earlier and its spec is gone, but it no longer starts with the generated header; delete it yourself', $plan->changes[0]->reason);
        $writer->apply($plan, $this->manifest, []);
        self::assertFileExists($this->directory->path . '/src/A.php');
        self::assertTrue($writer->plan($this->manifest, [])->isUpToDate());
    }

    public function testAnInterruptedRunLeavesEveryFileInTheManifest(): void
    {
        $writer = new FilesystemWriter();
        $old = [$this->file('src/Old.php', 'old')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);
        $this->directory->write('blocker', 'a file where a directory should be');
        $new = [$this->file('src/New.php', 'new'), $this->file('blocker/Item.php', 'blocked')];

        try {
            $writer->apply($writer->plan($this->manifest, $new), $this->manifest, $new);
            self::fail('The write into a file did not fail');
        } catch (WriteFailed $exception) {
            self::assertSame('Cannot create the directory ' . $this->directory->path . '/blocker', $exception->getMessage());
        }

        $manifest = json_decode((string) file_get_contents($this->manifest), true, flags: JSON_THROW_ON_ERROR);
        self::assertIsArray($manifest);
        self::assertSame(['blocker/Item.php', 'src/New.php', 'src/Old.php'], array_keys((array) $manifest['files']));
    }

    public function testApplyRefusesFilesThePlanWasNotMadeFor(): void
    {
        $writer = new FilesystemWriter();
        $plan = $writer->plan($this->manifest, [$this->file('src/ItemList.php', 'one')]);

        $this->expectException(LogicException::class);
        $this->expectExceptionMessage('The plan names a file it was not made for: ' . $this->directory->path . '/src/ItemList.php');
        $writer->apply($plan, $this->manifest, []);
    }

    public function testManifestWithoutFilesCountsAsEmpty(): void
    {
        file_put_contents($this->manifest, '{"generator": "msstc4php/dto-collection-generator"}');

        self::assertFalse((new FilesystemWriter())->plan($this->manifest, [])->manifestOutdated);
    }

    public function testManifestOrderDoesNotMatter(): void
    {
        $writer = new FilesystemWriter();
        $files = [$this->file('src/A.php', 'a'), $this->file('src/B.php', 'b')];
        $writer->apply($writer->plan($this->manifest, $files), $this->manifest, $files);
        file_put_contents($this->manifest, json_encode(['files' => [
            'src/B.php' => hash('sha256', self::HEADER . 'b'),
            'src/A.php' => hash('sha256', self::HEADER . 'a'),
        ]], JSON_THROW_ON_ERROR));

        self::assertTrue($writer->plan($this->manifest, $files)->isUpToDate());
    }

    public function testManifestKeysAreSortedAsWritten(): void
    {
        $root = new TemporaryDirectory();
        $manifest = $root->write('b-project/.dto-collection-generator.manifest.json', '');
        unlink($manifest);
        $files = [new GeneratedFile($root->path . '/b-project/a.php', self::HEADER), new GeneratedFile($root->path . '/c-outside/X.php', self::HEADER)];
        $writer = new FilesystemWriter();

        try {
            $writer->apply($writer->plan($manifest, $files), $manifest, $files);
            $written = json_decode((string) file_get_contents($manifest), true, flags: JSON_THROW_ON_ERROR);
            self::assertIsArray($written);
            self::assertSame(['../c-outside/X.php', 'a.php'], array_keys((array) $written['files']));
        } finally {
            $root->remove();
        }
    }

    public function testEmptyManifestIsAnObject(): void
    {
        $writer = new FilesystemWriter();
        $writer->apply($writer->plan($this->manifest, []), $this->manifest, []);

        self::assertSame("{\n    \"generator\": \"msstc4php/dto-collection-generator\",\n    \"files\": {}\n}\n", file_get_contents($this->manifest));
    }

    public function testManifestKeepsUnicodePaths(): void
    {
        $writer = new FilesystemWriter();
        $files = [$this->file('src/Ünicode.php', 'one')];
        $writer->apply($writer->plan($this->manifest, $files), $this->manifest, $files);

        self::assertStringContainsString('"src/Ünicode.php"', (string) file_get_contents($this->manifest));
    }

    public function testDeleteFailure(): void
    {
        if (function_exists('posix_geteuid') && posix_geteuid() === 0) {
            self::markTestSkipped('root can delete any file');
        }
        $writer = new FilesystemWriter();
        $old = [$this->file('locked/ItemList.php', 'one')];
        $writer->apply($writer->plan($this->manifest, $old), $this->manifest, $old);
        chmod($this->directory->path . '/locked', 0o555);

        try {
            $this->expectException(WriteFailed::class);
            $this->expectExceptionMessage('Cannot delete ' . $this->directory->path . '/locked/ItemList.php');
            $writer->apply($writer->plan($this->manifest, []), $this->manifest, []);
        } finally {
            chmod($this->directory->path . '/locked', 0o755);
        }
    }

    public function testWriteFailure(): void
    {
        if (function_exists('posix_geteuid') && posix_geteuid() === 0) {
            self::markTestSkipped('root can write anywhere');
        }
        $this->directory->write('locked/.keep', '');
        chmod($this->directory->path . '/locked', 0o555);
        $files = [$this->file('locked/ItemList.php', 'one')];
        $writer = new FilesystemWriter();

        try {
            $this->expectException(WriteFailed::class);
            $this->expectExceptionMessage('Cannot write ' . $this->directory->path . '/locked/ItemList.php');
            $writer->apply($writer->plan($this->manifest, $files), $this->manifest, $files);
        } finally {
            chmod($this->directory->path . '/locked', 0o755);
        }
    }

    public function testRecognisesGeneratedFiles(): void
    {
        $generated = $this->directory->write('src/Generated.php', self::HEADER . 'final class Generated {}');
        $crlf = $this->directory->write('src/Crlf.php', str_replace("\n", "\r\n", self::HEADER));
        $handWritten = $this->directory->write('src/HandWritten.php', "<?php\n\nfinal class HandWritten {}\n");
        $writer = new FilesystemWriter();

        self::assertTrue($writer->isGenerated($generated));
        self::assertTrue($writer->isGenerated($crlf));
        self::assertFalse($writer->isGenerated($handWritten));
        self::assertFalse($writer->isGenerated($this->directory->path . '/missing.php'));
    }

    public function testUnreadableManifestCountsAsEmpty(): void
    {
        file_put_contents($this->manifest, 'not json');

        self::assertSame([['create', 'src/ItemList.php']], $this->changes((new FilesystemWriter())->plan($this->manifest, [$this->file('src/ItemList.php', 'one')])));
    }

    private function file(string $relativePath, string $body): GeneratedFile
    {
        return new GeneratedFile($this->directory->path . '/' . $relativePath, self::HEADER . $body);
    }

    /**
     * @return list<array{string, string}>
     */
    private function changes(WritePlan $plan): array
    {
        return array_map(
            fn (FileChange $change): array => [$change->kind->value, substr($change->path, strlen($this->directory->path) + 1)],
            $plan->changes,
        );
    }
}
